-- ============================================================================
-- 0032_household_allergens.sql — 가구 단위 알러지 목록 (households.allergens)
-- ============================================================================
-- 배경: 지금까지는 재료 하나하나(IngredientDetailModal)에서 알러지 유발 성분을 직접
-- 입력해야 해서, "우리 가구는 마늘·밀가루를 피해요" 같은 단순한 사실 하나를 등록하려고
-- 재료를 일일이 찾아 들어가야 하는 번거로움이 있었음. 프로필에서 가구 단위로 한 번에
-- 관리하는 목록을 추가하고, 이름이 정확히 같은 기존 재료는 자동으로 태깅한다(예: "마늘"
-- 목록에 추가 → "마늘"이라는 이름의 재료가 있으면 자동으로 allergens에 반영). "돈까스소스"처럼
-- 이름만 봐서는 알 수 없는 재료는 여전히 재료 상세 화면에서 표시해야 하는데, 이제 그 화면의
-- 알러지 섹션이 이 목록을 토글 칩으로 제안해줘서 탭 한 번으로 끝난다.
--
-- 레시피의 알러지 필터(computeRecipeAllergens)는 그대로 ingredients.allergens를 집계하는
-- 방식이라 변경 없음 — 이 컬럼은 "입력을 더 쉽게 하는 관리용 목록"일 뿐, 레시피 계산에
-- 직접 쓰이지 않는다.
--
-- 실행 방법: Supabase 대시보드 > SQL Editor에서 이 파일 전체를 한 번 실행.
-- ============================================================================

alter table public.households add column if not exists allergens text[] not null default '{}';

-- RLS: households_update_member 정책(가구원이면 수정 가능)이 이미 있어서, 이 컬럼도 별도
-- 정책 추가 없이 그대로 커버된다(행 단위 정책이라 새 컬럼에도 자동 적용).
