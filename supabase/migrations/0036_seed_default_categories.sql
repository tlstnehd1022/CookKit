-- ============================================================================
-- 0036_seed_default_categories.sql — 재료 카테고리 기본 시딩 + 기존 household 백필
-- ============================================================================
-- 배경: 태그(요리스타일/국가장르)는 create_household()에서 자동으로 채워주는데, 재료
-- 카테고리는 그런 시딩이 없었다(예전 로컬스토리지 시절 seed.ts에만 있었고 Supabase 전환 후
-- 안 쓰임) — 신규 가구가 카테고리 0개로 시작해 "재료 직접 추가"가 막혀있었다. 내용도
-- 다시 정리: 계란이 낄 자리가 없던 "유제품"을 "계란·유제품"으로, 라면 등 가공식품이 낄
-- 자리가 없던 걸 "가공·냉동식품"으로 새로 추가, 과일 신설, 두부는 "육류·해산물·두부"로
-- (찌개 등에서 고기 대신 쓰이는 단백질 재료라는 점에서 같은 묶음이 자연스러움).
--
-- 실행 방법: Supabase 대시보드 > SQL Editor에서 이 파일 전체를 한 번 실행.
-- ============================================================================

insert into public.categories (household_id, name)
select h.id, v.name
from public.households h
cross join (
  values ('채소'), ('과일'), ('육류·해산물·두부'), ('계란·유제품'),
         ('곡류·면류'), ('소스·양념'), ('가공·냉동식품'), ('기타')
) as v(name)
where not exists (
  select 1 from public.categories c where c.household_id = h.id and c.name = v.name
);
